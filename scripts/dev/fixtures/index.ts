/**
 * Shared Float Index vectors: inputs listed here, expected outputs from the
 * TypeScript SDK, checked against float-core by
 * `crates/float-core/tests/index_vectors.rs`.
 *
 * Mints are written as one byte `b` meaning `[b; 32]`. Big integers are
 * strings. Every result is `{ "ok": value }` or `{ "err": "CoreErrorName" }`.
 */
import { PublicKey, floatIndex as x } from "@float-community/sdk";

type Result = { ok: unknown } | { err: string };

const run = (fn: () => unknown): Result => {
  try {
    const v = fn();
    return { ok: v === undefined ? true : v };
  } catch (e) {
    if (e instanceof x.IndexError) return { err: e.code };
    throw e;
  }
};
const str = (v: unknown): unknown =>
  typeof v === "bigint" ? v.toString() : Array.isArray(v) ? v.map(str) : v && typeof v === "object" ? Object.fromEntries(Object.entries(v).map(([k, y]) => [k, str(y)])) : v;
const key = (b: number) => new PublicKey(new Uint8Array(32).fill(b));

function xorshift(seed: bigint) {
  let s = seed;
  const M = (1n << 64n) - 1n;
  return (n: bigint) => {
    s ^= (s << 13n) & M;
    s ^= s >> 7n;
    s ^= (s << 17n) & M;
    return s % n;
  };
}

