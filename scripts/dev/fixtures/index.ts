function randomWeightCases() {
  const rnd = xorshift(0x2545f4914f6cdd1dn);
  return [...Array(8).keys()].map((k) => {
    const n = Number(1n + rnd(10n));
    const cands: C[] = [...Array(n).keys()].map((i) => [i + 1, rnd(1n << 50n), Number(500n + rnd(9_501n))]);
    const cap = Number(500n + rnd(9_501n));
    return [`xorshift ${k + 1}`, cands, cap] as [string, C[], number];
  });
}

