export function buildIndexVectors() {
  const weights = [...weightCases, ...randomWeightCases()].map(([name, cands, capBps]) => ({
    name,
    candidates: cands,
    capBps,
    expected: run(() => x.targetWeights(cands.map(([b, mcap, liq]) => ({ mint: key(b), mcap, liqCapBps: liq })), capBps)),
  }));
  return str({
    description: "Generated by scripts/dev/gen-fixtures.ts from scripts/dev/fixtures/index.ts. Do not edit by hand",
    spec: "docs/proposals/float-index.md",
    liquidityCaps: [
      [500_000n, 1_000_000n, 1_000],
      [500_000n, 0n, 1_000],
      [(1n << 64n) - 1n, 1n, 10_000],
      [50_000n, 3_000_000n, 1_000],
    ].map(([pool, aum, f]) => ({ poolPairedUsd: pool, aumUsd: aum, liqFactorBps: f, expected: x.liquidityCapBps(pool as bigint, aum as bigint, f as number) })),
    weights,
    creation: creationCases.map(([name, supply, qOld, qNew, tNet]) => ({ name, supply, qOld, qNew, tNet, expected: run(() => x.creationShares(supply, qOld, qNew, tNet)) })),
    tickets: [
      [9n, 1n, 3n],
      [10n, 1n, 3n],
      [10n, 4n, 3n],
      [10n, 0n, 0n],
    ].map(([s, t, total]) => ({ epochShares: s, ticket: t, epochTotal: total, expected: run(() => x.ticketShares(s!, t!, total!)) })),
    redeem: redeemCases.map(([q, amount, supply]) => ({ quantities: q, x: amount, supply, expected: run(() => x.redeemAmounts(q, amount, supply)) })),
    rewards: [
      [150n, 100n],
      [100n, 100n],
      [99n, 100n],
    ].map(([b, t]) => ({ balance: b, tracked: t, expected: run(() => x.rewardAvailable(b!, t!)) })),
    rebalance: rebalanceCases.map(([name, q, prices, targets, band, turnover]) => ({
      name,
      quantities: q,
      prices,
      targets,
      bandBps: band,
      turnoverBps: turnover,
      drift: run(() => x.driftBps(q, prices, targets)),
      expected: run(() => x.rebalancePlan(q, prices, targets, band, turnover)),
    })),
  });
}
