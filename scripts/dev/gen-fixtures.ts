/**
 * Regenerates cross-language test fixtures consumed by the Rust crates.
 *   node scripts/dev/gen-fixtures.ts
 *
 * Feature vectors are built in scripts/dev/fixtures/<feature>.ts, so the
 * TypeScript tests can check that the committed JSON is up to date.
 */
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { PublicKey, buildAirdropTree, toHex } from "@float-community/sdk";
import { buildFamilyVectors } from "./fixtures/family.ts";
import { buildLobbyVectors } from "./fixtures/lobby.ts";

const fixture = (name: string) => fileURLToPath(new URL(`../../crates/float-core/tests/fixtures/${name}`, import.meta.url));

function write(name: string, value: unknown) {
  const path = fixture(name);
  writeFileSync(path, JSON.stringify(value, null, 2) + "\n");
  console.log(`wrote ${path}`);
}

// ------------------------------------------------------------ airdrop merkle

const wallets = [1, 2, 3, 4].map((b) => new PublicKey(new Uint8Array(32).fill(b)));
const tree = buildAirdropTree(2n, wallets.map((w, i) => ({ wallet: w, amount: BigInt((i + 1) * 1_000_000) })));

write("airdrop-merkle.json", {
  description: "Generated by scripts/dev/gen-fixtures.ts — do not edit by hand",
  roundId: 2,
  root: toHex(tree.root),
  wallet0: toHex(wallets[0]!.bytes),
  amount0: 1000000,
  leaf0: toHex(tree.leaves[0]!.leaf),
  proof0: tree.leaves[0]!.proof.map(toHex),
});

// --------------------------------------------------------- feature proposals

write("family-vectors.json", buildFamilyVectors());
write("lobby-allocation.json", buildLobbyVectors());
